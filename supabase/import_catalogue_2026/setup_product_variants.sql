-- Product variants for flat products table
-- CONSTRAINTS:
--   * Does NOT change products.name
--   * Does NOT change products.image_url
--   * Keeps primary (lowest-price) product visible
--   * Hides sibling size rows from catalogue via is_active=false
--   * Sibling rows are kept (not deleted) so data/images remain intact
-- Source: products_rows__1_.csv (current DB after split)

begin;

-- 1) Flag to hide duplicate size rows from the app catalogue
alter table public.products
  add column if not exists is_active boolean not null default true;

-- 2) Variants table (one product, many pack sizes)
create table if not exists public.product_variants (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products (id) on delete cascade,
  label text not null,
  price numeric not null check (price >= 0),
  sort_order int not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (product_id, label)
);

create index if not exists product_variants_product_idx
  on public.product_variants (product_id, sort_order);

alter table public.product_variants enable row level security;

drop policy if exists "Anyone reads active product variants" on public.product_variants;
create policy "Anyone reads active product variants"
  on public.product_variants for select
  to anon, authenticated
  using (is_active = true);

