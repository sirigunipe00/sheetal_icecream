-- =============================================================================
-- Supabase Schema for Cart & Wishlist
-- Run this in your Supabase Dashboard -> SQL Editor
-- =============================================================================

-- 1. Create the 'cart_items' table
CREATE TABLE IF NOT EXISTS public.cart_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id text NOT NULL,
    product_id bigint NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
    quantity int NOT NULL DEFAULT 1 CHECK (quantity > 0),
    created_at timestamptz DEFAULT now(),
    updated_at timestamptz DEFAULT now(),
    CONSTRAINT cart_user_product_unique UNIQUE (user_id, product_id)
);

-- 2. Create the 'wishlist' table
CREATE TABLE IF NOT EXISTS public.wishlist (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id text NOT NULL,
    product_id bigint NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
    created_at timestamptz DEFAULT now(),
    CONSTRAINT wishlist_user_product_unique UNIQUE (user_id, product_id)
);

-- 3. Set up Row Level Security (RLS) policies
-- This allows both guest users and logged-in users to manage their cart & wishlist
ALTER TABLE public.cart_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.wishlist ENABLE ROW LEVEL SECURITY;

-- Cart Policies: allow all operations (select, insert, update, delete)
DROP POLICY IF EXISTS "Public cart access" ON public.cart_items;
CREATE POLICY "Public cart access" ON public.cart_items
    FOR ALL
    USING (true)
    WITH CHECK (true);

-- Wishlist Policies: allow all operations (select, insert, delete)
DROP POLICY IF EXISTS "Public wishlist access" ON public.wishlist;
CREATE POLICY "Public wishlist access" ON public.wishlist
    FOR ALL
    USING (true)
    WITH CHECK (true);

-- 4. Enable Supabase Realtime Replication & Publications
-- Set replica identity to FULL so that DELETE events include all column data
ALTER TABLE public.cart_items REPLICA IDENTITY FULL;
ALTER TABLE public.wishlist REPLICA IDENTITY FULL;

-- Add tables to the supabase_realtime publication
DO $$
BEGIN
  BEGIN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.cart_items;
  EXCEPTION WHEN duplicate_object THEN
    NULL;
  END;

  BEGIN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.wishlist;
  EXCEPTION WHEN duplicate_object THEN
    NULL;
  END;
END $$;

