#!/usr/bin/env python3
"""Generate supabase/seed.sql from lib/data/catalog/catalog_repository.dart.

Usage: python3 tool/generate_supabase_seed.py
"""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "lib/data/catalog/catalog_repository.dart"
OUTPUT = ROOT / "supabase/seed.sql"

STRING = r"""(?:'((?:[^'\\]|\\.)*)'|"((?:[^"\\]|\\.)*)")"""


def dart_string(match, first_group=1):
    raw = match.group(first_group)
    if raw is None:
        raw = match.group(first_group + 1)
    return re.sub(r"\\(.)", r"\1", raw)


def strings_in(text):
    return [dart_string(m) for m in re.finditer(STRING, text)]


def block(source, name):
    start = source.index(f"static const {name} = ")
    open_char = source[source.index("=", start) + 2]
    close_char = {"[": "]", "{": "}"}[open_char]
    i = source.index(open_char, start)
    depth = 0
    for j in range(i, len(source)):
        if source[j] == open_char:
            depth += 1
        elif source[j] == close_char:
            depth -= 1
            if depth == 0:
                return source[i + 1 : j]
    raise ValueError(f"Unclosed block {name}")


def field(text, name, kind):
    if kind == "int":
        m = re.search(rf"\b{name}:\s*(\d+)", text)
        return int(m.group(1)) if m else None
    if kind == "bool":
        m = re.search(rf"\b{name}:\s*(true|false)", text)
        return m.group(1) == "true" if m else False
    m = re.search(rf"\b{name}:\s*{STRING}", text)
    return dart_string(m) if m else None


def slug(name):
    return re.sub(r"[^a-z0-9]+", "-", name.lower().replace("&", "and")).strip("-")


def sql(value):
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def storage_path(folder, asset):
    return f"{folder}/{Path(asset).name}" if asset else None


def main():
    source = SOURCE.read_text()

    categories = [c for c in strings_in(block(source, "allCategories")) if c != "All"]

    images = {}
    for m in re.finditer(rf"{STRING}\s*:\s*{STRING}", block(source, "categoryImageMap")):
        images[dart_string(m, 1)] = dart_string(m, 3)

    segments = []
    for m in re.finditer(
        rf"CategorySegment\(\s*name:\s*{STRING},\s*categoryNames:\s*\[(.*?)\]",
        block(source, "segmentList"),
        re.S,
    ):
        segments.append((dart_string(m), strings_in(m.group(3))))

    products = []
    for chunk in re.split(r"\bProduct\(", block(source, "allProducts"))[1:]:
        products.append(
            {
                "id": field(chunk, "id", "int"),
                "name": field(chunk, "name", "str"),
                "unit": field(chunk, "unit", "str"),
                "price": field(chunk, "price", "int"),
                "category": field(chunk, "category", "str"),
                "image": field(chunk, "image", "str"),
                "description": field(chunk, "description", "str"),
                "is_new": field(chunk, "isNew", "bool"),
                "key": field(chunk, "key", "str"),
            }
        )

    best_sellers = [
        int(i)
        for i in re.findall(
            r"allProducts\[(\d+)\]",
            source[source.rindex("get bestSellers") : source.rindex("get newArrivals")],
        )
    ]

    segment_of = {c: slug(name) for name, cats in segments for c in cats}
    missing = [c for c in categories if c not in segment_of]
    unknown = sorted({p["category"] for p in products} - set(categories))
    ids = [p["id"] for p in products]
    if missing or unknown or len(set(ids)) != len(ids) or None in ids:
        raise SystemExit(f"Catalog mismatch: missing={missing} unknown={unknown}")

    lines = [
        "-- Generated by tool/generate_supabase_seed.py from",
        "-- lib/data/catalog/catalog_repository.dart. Do not edit by hand.",
        "-- Safe to run more than once: existing rows are left untouched.",
        "",
        "begin;",
        "",
        "insert into public.segments (id, name, sort_order) values",
    ]
    lines.append(
        ",\n".join(
            f"  ({sql(slug(name))}, {sql(name)}, {i})" for i, (name, _) in enumerate(segments)
        )
        + "\non conflict (id) do nothing;"
    )

    lines += ["", "insert into public.categories (id, segment_id, name, image_path, sort_order) values"]
    lines.append(
        ",\n".join(
            f"  ({sql(slug(c))}, {sql(segment_of[c])}, {sql(c)}, "
            f"{sql(storage_path('categories', images.get(c)))}, {i})"
            for i, c in enumerate(categories)
        )
        + "\non conflict (id) do nothing;"
    )

    lines += [
        "",
        "insert into public.products",
        "  (id, legacy_key, category_id, name, description, image_path, is_new, best_seller_rank)",
        "overriding system value values",
    ]
    rank = {pid: i + 1 for i, pid in enumerate(best_sellers)}
    lines.append(
        ",\n".join(
            f"  ({p['id']}, {sql(p['key'])}, {sql(slug(p['category']))}, {sql(p['name'])}, "
            f"{sql(p['description'])}, {sql(storage_path('products', p['image']))}, "
            f"{sql(p['is_new'])}, {sql(rank.get(p['id']))})"
            for p in products
        )
        + "\non conflict (id) do nothing;"
    )

    lines += [
        "",
        "select setval(",
        "  pg_get_serial_sequence('public.products', 'id'),",
        "  (select max(id) from public.products)",
        ");",
        "",
        "insert into public.product_images (product_id, storage_path, sort_order) values",
    ]
    lines.append(
        ",\n".join(
            f"  ({p['id']}, {sql(storage_path('products', p['image']))}, 0)"
            for p in products
            if p["image"]
        )
        + "\non conflict (product_id, storage_path) do nothing;"
    )

    lines += [
        "",
        "insert into public.product_variants",
        "  (product_id, sku, label, units_per_pack, price, mrp, sort_order) values",
    ]
    variants = []
    for p in products:
        pid, price = p["id"], p["price"]
        variants.append(f"  ({pid}, 'SHT-{pid:04d}-1', {sql(p['unit'])}, 1, {price}, null, 0)")
        variants.append(
            f"  ({pid}, 'SHT-{pid:04d}-4', 'Pack of 4', 4, {price * 4 - 15}, {price * 4}, 1)"
        )
    lines.append(",\n".join(variants) + "\non conflict (sku) do nothing;")

    lines += [
        "",
        "-- Every product starts with 0 units in stock. Enter real counts after a",
        "-- physical stock check, either from the admin app (admin_adjust_stock) or",
        "-- from the SQL editor, for example:",
        "--",
        "-- select private.apply_inventory_change(",
        "--   product_id, 'opening_stock', <units>, 0, null, 'Opening stock count', null",
        "-- ) from public.products where id = 0;",
        "",
        "commit;",
        "",
    ]

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines))
    print(
        f"Wrote {OUTPUT.relative_to(ROOT)}: {len(segments)} segments, {len(categories)} categories, "
        f"{len(products)} products, {len(variants)} variants, {len(best_sellers)} best sellers"
    )


if __name__ == "__main__":
    main()
